/**
 * The crew's cards and lenses (plan section 2): generated, never written by
 * hand. A card (3 KB or less) is a specialist's remit, its lints and checks,
 * and the doctrine it applies, taken sentence by sentence from the playbook
 * sections crew/index.json names; each source is recorded by its SHA-256 so
 * a playbook that changes without its card being regenerated is drift
 * (scripts/check-crew.mjs). A lens (1 KB or less) is one question for an
 * independent reviewer. Pure: it takes the sources' text, returns the files.
 */
import { createHash } from 'node:crypto';

export const CARD_MAX = 3072;
export const LENS_MAX = 1024;
const sha = text => createHash('sha256').update(text).digest('hex');

/** The body of one section: everything under its heading to the next heading of the same or a higher level. */
export function section(markdown, heading) {
  const lines = String(markdown).split('\n');
  const at = lines.findIndex(l => /^#{2,6} /.test(l) && l.replace(/^#+ /, '').trim() === heading);
  if (at < 0) return null;
  const level = /^#+/.exec(lines[at])[0].length;
  const end = lines.findIndex((l, i) => i > at && new RegExp(`^#{1,${level}} `).test(l));
  return lines.slice(at + 1, end < 0 ? undefined : end).join('\n');
}

/** Each paragraph or list item of a section, unwrapped, with links reduced to their words and emphasis removed. */
export function pieces(body) {
  const out = [];
  let current = null;
  for (const raw of String(body).split('\n')) {
    const line = raw.trim();
    if (!line || line.startsWith('```') || line.startsWith('|')) { if (current) out.push(current); current = null; continue; }
    if (/^(?:[-*]|\d+\.)\s+/.test(line)) { if (current) out.push(current); current = line.replace(/^(?:[-*]|\d+\.)\s+/, ''); continue; }
    current = current ? `${current} ${line}` : line;
  }
  if (current) out.push(current);
  return out.map(p => p.replace(/^\*\*([^*]+?)[.:]\*\*\s+/, '$1: ').replace(/\[([^\]]+)\]\([^)]+\)/g, '$1').replace(/\*\*([^*]+)\*\*/g, '$1').replace(/\s+/g, ' ').trim()).filter(Boolean);
}

/** The first sentence of a piece: up to the first full stop that ends a sentence. */
export function lead(piece) {
  const m = /^(.+?[.!?])(?:\s+(?=["'(`]?[A-Z0-9])|$)/.exec(piece);
  return (m ? m[1] : piece).trim();
}

/** The card for one specialist, from its sources' text by path. Throws when a section it names is gone, so a rename is caught. */
export function cardFor(s, texts) {
  const head = [
    `# ${s.name}`,
    '',
    `Generated by scripts/check-crew.mjs from crew/index.json and the sources below. Do not edit by hand.`,
    '',
    `Reviews: ${s.reviews}. Lanes: ${s.lanes.join(', ')}.`,
    `Lints (shadow until the switch): ${s.lints.join(', ')}.`,
    `Measured checks: ${s.checks.join(', ')}.`,
    `Lens: ${s.lens}`,
    '',
    '## Doctrine',
    ''
  ].join('\n');
  const foot = ['', '## Sources', '', ...s.sources.map(x => `- ${x.file}, "${x.heading}": sha256 ${sha(texts[x.file]).slice(0, 16)}`), ''].join('\n');
  const room = CARD_MAX - Buffer.byteLength(head) - Buffer.byteLength(foot);
  const share = Math.floor(room / s.sources.length);
  const body = [];
  for (const x of s.sources) {
    const text = section(texts[x.file] ?? '', x.heading);
    if (text === null) throw new Error(`${s.slug}: ${x.file} has no section "${x.heading}"`);
    let used = 0;
    const title = `From ${x.file.split('/').at(-1)}, ${x.heading}:\n`;
    const lines = [];
    for (const p of pieces(text)) {
      const line = `- ${lead(p)}\n`;
      if (used + Buffer.byteLength(title) + Buffer.byteLength(line) > share - 2) break;
      lines.push(line); used += Buffer.byteLength(line);
    }
    body.push(`${title}${lines.join('')}`);
  }
  return `${head}${body.join('\n')}${foot}`;
}

/** The lens for one specialist: the one question, and what it is asked of. */
export function lensFor(s) {
  return [`# ${s.name}: the lens`, '', `Generated by scripts/check-crew.mjs from crew/index.json. Do not edit by hand.`, '', `Ask of every action this specialist reviews (${s.reviews}): ${s.lens}`, '', `Answer yes or no with the one line of the action that decides it. A no is reported with that line for Krish's read; the reviewer never edits the action.`, ''].join('\n');
}
